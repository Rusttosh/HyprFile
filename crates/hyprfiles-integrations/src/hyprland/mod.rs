use anyhow::{Context, Result};
use serde::Deserialize;
use tracing::{debug, trace, warn};

/// Detect if Hyprland is the current compositor.
/// Checks `HYPRLAND_INSTANCE_SIGNATURE` env var or availability of `hyprctl`.
pub fn detect_hyprland() -> bool {
    if std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some() {
        trace!("HYPRLAND_INSTANCE_SIGNATURE detected");
        return true;
    }
    if which::which("hyprctl").is_ok() {
        trace!("hyprctl found in PATH");
        return true;
    }
    false
}

/// Information about a monitor.
#[derive(Debug, Clone, Deserialize)]
pub struct MonitorInfo {
    pub id: u64,
    pub name: String,
    pub description: String,
    pub width: u64,
    pub height: u64,
    pub refresh_rate: f64,
    pub x: i64,
    pub y: i64,
    pub active_workspace: WorkspaceRef,
    pub reserved: Vec<u64>,
    pub scale: f64,
    pub transform: u64,
    pub dpms: bool,
    pub vrr: Option<bool>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct WorkspaceRef {
    pub id: u64,
    pub name: String,
}

/// Information about a workspace.
#[derive(Debug, Clone, Deserialize)]
pub struct WorkspaceInfo {
    pub id: u64,
    pub name: String,
    pub monitor: String,
    pub windows: u64,
    pub hasfullscreen: bool,
    pub lastwindow: String,
    pub lastwindowtitle: String,
}

/// Query `hyprctl monitors -j` and return parsed info.
pub async fn get_active_monitor() -> Result<MonitorInfo> {
    if !detect_hyprland() {
        anyhow::bail!("Hyprland not detected");
    }
    let output = tokio::process::Command::new("hyprctl")
        .args(["monitors", "-j"])
        .output()
        .await
        .context("Failed to execute hyprctl monitors -j")?;
    if !output.status.success() {
        anyhow::bail!(
            "hyprctl exited with status {:?}",
            output.status.code()
        );
    }
    let monitors: Vec<MonitorInfo> =
        serde_json::from_slice(&output.stdout).context("Failed to parse hyprctl JSON")?;
    monitors
        .into_iter()
        .next()
        .context("No monitors reported by hyprctl")
}

